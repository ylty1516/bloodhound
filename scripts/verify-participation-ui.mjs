import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const text=fs.readFileSync(new URL('../web/participation.js',import.meta.url),'utf8');
const context=vm.createContext({array:x=>Array.isArray(x)?x:[],checkHostLabels:{codex:'Codex',claude:'Claude Code',deepseek_api:'DeepSeek API'}});
vm.runInContext(text.slice(text.indexOf('function participationAgent('),text.indexOf('\nfunction participationStep(')),context);
vm.runInContext(text.slice(text.indexOf('function participationStep('),text.indexOf('\nfunction startParticipation(')),context);
const candidate={id:'c',name:'Synthetic project'};
const state={candidates:[candidate],agent_checks:[],preparation_plans:[]};
const step=(s=state,jobs=[])=>context.participationStep(s,'c','any',jobs);
assert.equal(context.participationStep(state,null).phase,'choose');
assert.equal(step().action,'check');
const job={id:'check',candidate_id:'c',status:'running',current:true,progress:'实际读取中'};
assert.equal(step({...state,agent_checks:[job]}).action,'checking');
assert.equal(step({...state,agent_checks:[{...job,status:'failed'}]}).phase,'retry');
assert.equal(step({...state,agent_checks:[{...job,status:'completed',current:false}]}).phase,'stale');
const completed={...job,status:'completed'};
assert.equal(step({...state,agent_checks:[completed]}).phase,'report');
const plan={id:'p',check_id:'check',candidate_id:'c',execution_drivers:[],recommendation:{status:'needs_security_review'}};
const prepared={...state,agent_checks:[completed],preparation_plans:[plan]};
assert.equal(step(prepared).action,'plan');
assert.match(step(prepared).note,/没有接入/);
const supported={...prepared,preparation_plans:[{...plan,execution_drivers:['testnet']} ]};
assert.equal(step(supported).phase,'blocked');
assert.equal(step(supported).label,'查看启动条件');
const reviewed={...prepared,preparation_plans:[{...plan,execution_drivers:['testnet'],recommendation:{status:'suggested_trial'}}]};
assert.equal(step(reviewed).phase,'configure');
const running={id:'run',mode:'live',status:'running',binding:{candidate_id:'c'},message:'实际运行中'};
assert.equal(step(reviewed,[running]).action,'run-progress');
assert.notEqual(step(reviewed,[{...running,mode:'diagnostic'}]).action,'run-progress');
assert.equal(step(reviewed,[{...running,status:'completed'}]).action,'configure');
assert.equal(step(reviewed,[{...running,binding:{candidate_id:'other'}}]).action,'configure');
assert.equal(step({...reviewed,agent_checks:[{...completed,id:'new-failed',status:'failed'}]}).plan.id,'p');
assert.equal(context.participationAgent({agent_context:{status:'detected',host:'codex'},agent_settings:{policy:{default_host:'deepseek_api'}}}).host,'codex');
assert.equal(context.participationAgent({agent_check_hosts:[{id:'codex',dispatch:'native_cli'}]}).host,null);
assert.equal(context.participationAgent({agent_context:{status:'ambiguous'}}).unresolved,true);
assert.equal(context.participationAgent({agent_context:{status:'detected',host:'claude'}},'current',{status:'running',host:'codex'}).host,'codex');
assert.equal(context.participationAgent({},'deepseek_api').automatic,false);
assert.equal(context.participationAgent({},'deepseek_api').host,'deepseek_api');
const missing={...state,candidates:[{...candidate,launch:{status:'not_integrated',reason:'Software missing'}}],agent_checks:[{...completed,status:'failed'}]};
assert.equal(step(missing).phase,'not_integrated');assert.equal(step(missing).action,'details');
const waiting={...reviewed,candidates:[{...candidate,launch:{status:'preparing',can_configure:false}}]};
assert.equal(step(waiting).phase,'prepare');assert.equal(step(waiting).action,'check');
assert.equal(step({...waiting,candidates:[{...candidate,launch:{status:'ready',can_configure:true}}]}).action,'configure');
assert.equal(step({...waiting,candidates:[{...candidate,launch:{status:'unsafe',label:'Safety concern'}}]}).phase,'blocked');
console.log(JSON.stringify({passed:28,checks:'participation states, live host selection, actual backend readiness, missing software is not a failed check, program safety pending, active job binding'}));
